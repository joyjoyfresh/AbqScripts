def paragraph_by_prefix(doc, prefix):  # 按段首唯一定位待更新段落
    """返回唯一匹配段落，防止误改同名章节或正文。"""
    matches = [p for p in doc.paragraphs if p.text.startswith(prefix)]  # 搜索段首文本
    if len(matches) != 1:  # 必须唯一命中
        raise RuntimeError("无法唯一定位段落：%s（匹配数=%d）" % (prefix, len(matches)))  # 中止错误更新
    return matches[0]  # 返回目标段落


def replace_prefix(doc, prefix, text):  # 替换段落文本并保留原段落样式
    """以最小范围替换既有段落内容。"""
    paragraph = paragraph_by_prefix(doc, prefix)  # 定位原段落
    paragraph.text = text  # 替换正文
    return paragraph  # 便于后续使用


def insert_after(paragraph, text):  # 在指定段落后插入同样式正文
    """插入一个与锚点同段落样式的连续正文段。"""
    element = OxmlElement("w:p")  # 新建 OOXML 段落元素
    paragraph._p.addnext(element)  # 插入到锚点之后
    new_paragraph = Paragraph(element, paragraph._parent)  # 包装为 python-docx 段落
    new_paragraph.style = paragraph.style  # 继承正文样式
    new_paragraph.add_run(text)  # 写入正文
    return new_paragraph  # 返回新段落


def set_table_text(cell, text):  # 用单段文本更新表格单元
    """清空单元格并写入一段规范文本。"""
    cell.text = text  # 保持原表格结构，只更新文字


