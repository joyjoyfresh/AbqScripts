def split_code_comment(line):
    code = []
    i = 0
    n = len(line)
    in_s = None
    while i < n:
        ch = line[i]
        if in_s:
            code.append(ch)
            if ch == BACKSLASH:
                if i + 1 < n:
                    code.append(line[i + 1])
                    i += 2
                    continue
            elif ch == in_s:
                in_s = None
            i += 1
            continue
        if ch in ('"', "'"):
            in_s = ch
            code.append(ch)
            i += 1
            continue
        if ch == '#':
            return ''.join(code), '#', line[i + 1:]
        code.append(ch)
        i += 1
    return ''.join(code), '', ''


in_doc = False
cands = []
for no, ln in enumerate(lines, 1):
    if '"""' in ln:
        if ln.count('"""') % 2 == 1:
            in_doc = not in_doc
        continue
    if in_doc:
        continue
    s = ln.lstrip()
    if s.startswith('#'):
        continue
    code, sep, cmt = split_code_comment(ln)
    if not sep:
        continue
    t = cmt.strip()
    if not t:
        continue
    if any(kw in t for kw in intent_kw):
        continue
    for pf in delete_prefixes:
        if t.startswith(pf):
            cands.append((no, t))
            break

out = io.open("redundant_cands.txt", "w", encoding="utf-8")
for no, t in cands:
    out.write("%d\t%s\n" % (no, t))
out.close()
print("redundant candidates:", len(cands))
