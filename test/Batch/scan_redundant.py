cands = []
for no, ln in enumerate(lines, 1):
    if '"""' in ln:
        if ln.count('"""') % 2 == 1:
            in_doc = not in_doc
        continue
    if in_doc:
        continue
    s = ln.lstrip()
    if s.startswith('#'):
        continue
    code, sep, cmt = split_code_comment(ln)
    if not sep:
        continue
    t = cmt.strip()
    if not t:
        continue
    if any(kw in t for kw in keep_kw):
        continue
    for pf in trivial_starts:
        if t.startswith(pf):
            cands.append((no, t))
            break

out = io.open("redundant_cands.txt", "w", encoding="utf-8")
for no, t in cands:
    out.write("%d\t%s\n" % (no, t))
out.close()
