def split_code_comment(line):
    code = []
    i = 0
    n = len(line)
    in_s = None
    while i < n:
        ch = line[i]
        if in_s:
            code.append(ch)
            if ch == BACKSLASH:
                if i + 1 < n:
                    code.append(line[i + 1])
                    i += 2
                    continue
            elif ch == in_s:
                in_s = None
            i += 1
            continue
        if ch in ('"', "'"):
            in_s = ch
            code.append(ch)
            i += 1
            continue
        if ch == '#':
            return ''.join(code), '#', line[i + 1:]
        code.append(ch)
        i += 1
    return ''.join(code), '', ''


